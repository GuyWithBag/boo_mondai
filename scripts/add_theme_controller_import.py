#!/usr/bin/env python3
"""Add the ThemeController import to Dart files that use it.

Preview changes without writing:

    python3 scripts/add_theme_controller_import.py --dry-run

Apply the changes:

    python3 scripts/add_theme_controller_import.py
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path


THEME_CONTROLLER_IMPORT = (
    "import 'package:boo_mondai/lib.barrel.dart' show ThemeController;"
)
THEME_CONTROLLER_USAGE = re.compile(r"\bThemeController\b")
THEME_CONTROLLER_IMPORT_USAGE = re.compile(
    r"import\s+['\"]package:boo_mondai/(?:lib\.barrel\.dart|core/theme/theme\.barrel\.dart|core/theme/theme\.controller\.dart)['\"]"
)
GENERATED_FILE_MARKER = "generated by tool/generate_barrels.py"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Add the ThemeController import to Dart files that need it."
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=Path("lib"),
        help="Directory to scan (default: lib).",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show files that would change without modifying them.",
    )
    return parser.parse_args()


def needs_import(source: str) -> bool:
    if GENERATED_FILE_MARKER in source:
        return False
    if not THEME_CONTROLLER_USAGE.search(source):
        return False
    return not THEME_CONTROLLER_IMPORT_USAGE.search(source)


def insert_import(source: str) -> str:
    import_match = re.search(r"(?m)^import\s+", source)
    if import_match is not None:
        return (
            source[: import_match.start()]
            + THEME_CONTROLLER_IMPORT
            + "\n"
            + source[import_match.start() :]
        )

    return THEME_CONTROLLER_IMPORT + "\n\n" + source


def dart_files(root: Path) -> list[Path]:
    return sorted(
        path
        for path in root.rglob("*.dart")
        if ".dart_tool" not in path.parts and "build" not in path.parts
    )


def main() -> int:
    args = parse_args()
    if not args.root.exists():
        raise SystemExit(f"Scan directory does not exist: {args.root}")

    changed_files: list[Path] = []
    for path in dart_files(args.root):
        source = path.read_text(encoding="utf-8")
        if not needs_import(source):
            continue

        changed_files.append(path)
        if not args.dry_run:
            path.write_text(insert_import(source), encoding="utf-8")

    action = "Would update" if args.dry_run else "Updated"
    for path in changed_files:
        print(f"{action}: {path}")
    print(f"{action} {len(changed_files)} file(s).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
