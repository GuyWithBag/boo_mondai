#!/usr/bin/env python3
"""Generate Dart barrel files without build_runner.

This mirrors the previous barrel_generator config from lib/main.dart:
every folder under lib gets a `<folder_name>.barrel.dart` file, except for
the configured excluded files.
"""

from __future__ import annotations

import argparse
import fnmatch
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
LIB = ROOT / "lib"
EXPORT_RE = re.compile(r"^export '([^']+)';")
EXCLUDED_PATTERNS = (
    "lib/core/hive/hive.barrel.dart",
    "lib/core/helpers/image_file_provider_io.dart",
    "lib/core/helpers/image_file_provider_stub.dart",
    "lib/**/**/*.mapper.dart",
    "lib/**/*.mapper.dart",
    "lib/*.mapper.dart",
)


def relative_path(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def is_excluded(path: Path) -> bool:
    rel_path = relative_path(path)
    return any(fnmatch.fnmatch(rel_path, pattern) for pattern in EXCLUDED_PATTERNS)


def barrel_path(directory: Path) -> Path:
    if directory == LIB:
        return directory / "lib.barrel.dart"

    return directory / f"{directory.name}.barrel.dart"


def current_exports(barrel: Path) -> tuple[list[str], list[str]]:
    if not barrel.exists():
        return [], []

    section: str | None = None
    barrel_exports: list[str] = []
    file_exports: list[str] = []

    for raw_line in barrel.read_text().splitlines():
        line = raw_line.strip()
        if line == "// Barrel files":
            section = "barrels"
            continue
        if line == "// Other files":
            section = "files"
            continue

        match = EXPORT_RE.match(line)
        if match == None:
            continue

        if section == "barrels":
            barrel_exports.append(match.group(1))
        elif section == "files":
            file_exports.append(match.group(1))

    return barrel_exports, file_exports


def ordered_exports(existing: list[str], discovered: set[str]) -> list[str]:
    ordered = [path for path in existing if path in discovered]
    ordered_set = set(ordered)
    ordered.extend(path for path in sorted(discovered) if path not in ordered_set)
    return ordered


def discovered_exports(barrel: Path) -> tuple[set[str], set[str]]:
    directory = barrel.parent

    barrel_exports = {
        child_barrel.relative_to(directory).as_posix()
        for child_dir in directory.iterdir()
        if child_dir.is_dir()
        for child_barrel in [barrel_path(child_dir)]
        if not is_excluded(child_barrel)
        and has_exports(child_dir)
    }

    file_exports = {
        child.relative_to(directory).as_posix()
        for child in directory.glob("*.dart")
        if child != barrel
        and not is_excluded(child)
        and not child.name.startswith(".")
    }

    return barrel_exports, file_exports


def has_exports(directory: Path) -> bool:
    barrel = barrel_path(directory)
    discovered_barrels, discovered_files = discovered_exports(barrel)
    return len(discovered_barrels) > 0 or len(discovered_files) > 0


def build_barrel_text(barrel: Path) -> str:
    existing_barrels, existing_files = current_exports(barrel)
    discovered_barrels, discovered_files = discovered_exports(barrel)
    barrel_exports = ordered_exports(existing_barrels, discovered_barrels)
    file_exports = ordered_exports(existing_files, discovered_files)

    lines = [
        "// This file is generated by tool/generate_barrels.py",
        "",
        "// Barrel files",
    ]
    lines.extend(f"export '{path}';" for path in barrel_exports)
    lines.append("// Other files")
    lines.extend(f"export '{path}';" for path in file_exports)
    return "\n".join(lines) + "\n"


def generate(check: bool) -> int:
    changed: list[Path] = []
    barrels = {
        barrel_path(directory)
        for directory in [LIB, *LIB.rglob("*")]
        if directory.is_dir()
        and not is_excluded(barrel_path(directory))
        and has_exports(directory)
    }

    for barrel in sorted(barrels):
        next_text = build_barrel_text(barrel)
        current_text = barrel.read_text() if barrel.exists() else ""
        if next_text == current_text:
            continue

        changed.append(barrel)
        if not check:
            barrel.write_text(next_text)

    if changed:
        for path in changed:
            print(path.relative_to(ROOT))
        if check:
            print(f"{len(changed)} barrel file(s) are out of date.")
            return 1

    print(f"{'Checked' if check else 'Generated'} {len(barrels)} barrel file(s).")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="Report out-of-date barrels without writing files.",
    )
    args = parser.parse_args()
    return generate(check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
